#!/usr/bin/env python3
"""Reference for tests/lib_run/sha256.bmb (backlog T4-01).

    python3 sha256_ref.py > sha256.out     # the expected output
    python3 sha256_ref.py --emit-bmb       # the `cavp_short` function of sha256.bmb

The NIST CAVP lines are the digests in `sha256_cavp/*.rsp` (SHAVS byte-oriented
`SHA256ShortMsg.rsp` and `SHA256Monte.rsp`, CAVS 11.0/11.1, from the copy in
pyca/cryptography's test vectors: csrc.nist.gov is not reachable from the
environment this was made in). Every other line is Python's `hashlib.sha256`,
and the CAVP digests are checked against `hashlib` too.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
M64 = (1 << 64) - 1


def rsp(name):
    """(key, value) pairs of a CAVP response file, in order."""
    out = []
    with open(os.path.join(HERE, "sha256_cavp", name)) as f:
        for line in f:
            line = line.strip()
            if " = " in line and not line.startswith("#") and not line.startswith("["):
                k, v = line.split(" = ", 1)
                out.append((k, v))
    return out


def short_msgs():
    """(message, digest) of SHA256ShortMsg.rsp."""
    pairs, length, msg = [], None, None
    for k, v in rsp("SHA256ShortMsg.rsp"):
        if k == "Len":
            length = int(v)
        elif k == "Msg":
            msg = bytes.fromhex(v)[: length // 8]
        elif k == "MD":
            pairs.append((msg, v))
    return pairs


def monte():
    """(seed, digests) of SHA256Monte.rsp."""
    seed, mds = None, []
    for k, v in rsp("SHA256Monte.rsp"):
        if k == "Seed":
            seed = bytes.fromhex(v)
        elif k == "MD":
            mds.append(v)
    return seed, mds


def monte_check(seed, mds):
    """SHAVS §6.4 with hashlib, against the file."""
    s = seed
    for j in range(100):
        a = b = c = s
        for _ in range(3, 1003):
            a, b, c = b, c, hashlib.sha256(a + b + c).digest()
        s = c
        assert s.hex() == mds[j], f"Monte checkpoint {j}"


def stream(n):
    x, out = 2024, bytearray()
    for _ in range(n):
        x = (x * 6364136223846793005 + 1442695040888963407) & M64
        out.append(x >> 56)
    return bytes(out)


def h(m):
    return hashlib.sha256(m).hexdigest()


def main():
    shorts = short_msgs()
    seed, mds = monte()
    assert len(shorts) == 65 and len(mds) == 100
    for m, md in shorts:
        assert h(m) == md
    monte_check(seed, mds)
    if sys.argv[1:] == ["--emit-bmb"]:
        print("    // SHA256ShortMsg.rsp: the 65 messages of 0 to 64 bytes (generated by sha256_ref.py --emit-bmb).")
        print("    #[effects(io)]")
        print("    #[uses(sha256::msg_ok)]")
        print("    fn cavp_short() -> () {")
        for m, _ in shorts:
            lit = "".join(f"\\x{b:02x}" for b in m)
            print(f'        hex(sha256::digest(b"{lit}"));')
        print("    }")
        return
    # FIPS 180-4 / NIST examples.
    print(h(b"abc"))
    print(h(b""))
    print(h(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"))
    print(h(b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"))
    print(h(b"a" * 1000000))
    # CAVP.
    for _, md in shorts:
        print(md)
    for md in mds:
        print(md)
    # Prefixes of a pseudo-random stream: every length to 200 (the block
    # boundaries 55, 56, 63, 64, 65, 119, 120, 127, 128, ...), and longer ones.
    s = stream(70000)
    for n in range(201):
        print(h(s[:n]))
    for n in (1000, 4095, 4096, 4097, 65536, 70000):
        print(h(s[:n]))


main()
